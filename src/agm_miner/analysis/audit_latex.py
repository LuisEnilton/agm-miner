"""LaTeX output of the sampling audit, for the paper (Portuguese, SBC template).

Two files, both regenerated by every ``agm audit``:

* ``audit.tex``: one macro per number (``\\auditKept``, ``\\auditCoverageClaude``, ...) and one
  macro per table (``\\auditTableSelection``, ...). The paper loads it once (``\\input{audit}``
  in the preamble) and places the tables where it wants them, so a new audit updates every
  number of the text;
* ``audit_rascunho.tex``: a draft of the methodology and threats-to-validity paragraphs written
  with those macros, to be copied into the paper and edited there. Its first lines list the
  current warnings as comments.

Tables use only ``tabular`` and ``\\hline`` (no extra packages), as the SBC template asks for
plain tables. Numbers follow the Brazilian format (``5.380``, ``9,5\\%``).
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from datetime import date, datetime
from typing import Any

from agm_miner.config import SelectionConfig

AUDIT_TEX, DRAFT_TEX = "audit.tex", "audit_rascunho.tex"
FILE_TYPE_SUFFIX = {"CLAUDE.md": "Claude", "AGENTS.md": "Agents", "SKILL.md": "Skill"}
MISSING = "---"
# Cutoff of the related studies (projects older than the agent tools); the default of
# ``SelectionConfig.created_before``. The share of kept repositories created since then tells
# how far the sample departs from those studies.
RELATED_CUTOFF: date = SelectionConfig.model_fields["created_before"].default
_MACRO_RE = re.compile(r"^audit[A-Za-z]+$")
_SPECIAL = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


# --------------------------------------------------------------------------- formatting


def escape(text: str) -> str:
    """Text safe inside LaTeX."""
    return "".join(_SPECIAL.get(char, char) for char in text)


def number(value: float | None) -> str:
    """Integer with the Brazilian thousands separator (``5.380``)."""
    if value is None:
        return MISSING
    return f"{round(value):,}".replace(",", ".")


def percent(share: float | None) -> str:
    """Share as a percentage: whole numbers, one decimal below 10% (``9,5\\%``)."""
    if share is None:
        return MISSING
    value = 100 * share
    if 0 < value < 0.05:
        return r"$<$0,1\%"
    if value != 0 and value < 10:
        return f"{value:.1f}".replace(".", ",") + r"\%"
    return f"{value:.0f}" + r"\%"


def day(value: str | None) -> str:
    """ISO timestamp or date as ``dd/mm/aaaa``."""
    if not value:
        return MISSING
    return datetime.fromisoformat(value).strftime("%d/%m/%Y")


def camel(name: str) -> str:
    """``min_stars`` -> ``MinStars`` (macro names only take letters)."""
    return "".join(part.capitalize() for part in re.split(r"[^A-Za-z]+", name) if part)


# --------------------------------------------------------------------------- macros


def _share(part: int, whole: int) -> float | None:
    return part / whole if whole else None


def macro_values(audit: Mapping[str, Any]) -> dict[str, str]:
    """Every macro of ``audit.tex`` (name without backslash -> formatted LaTeX value)."""
    config = audit["study_config"]
    discovery, selection = audit["discovery"], audit["selection"]
    mining, artifacts = audit["mining"], audit["artifacts"]
    outside = discovery["outside_protocol"]
    values: dict[str, str] = {
        "auditExportDate": day(audit.get("exported_at")),
        "auditSizeMin": number(config["discovery"]["size_min"]),
        "auditSizeMax": number(config["discovery"]["size_max"]),
        "auditResultCap": number(config["discovery"]["max_results_per_query"]),
        "auditMinStars": number(config["selection"]["min_stars"]),
        "auditMinCommits": number(config["selection"]["min_commits"]),
        "auditActiveDays": number(config["selection"]["active_within_days"]),
        "auditCreatedBefore": day(config["selection"]["created_before"]),
        "auditReferenceDate": day(selection["reference_date"]),
        "auditMinArtifactBytes": number(config["analysis"]["min_artifact_bytes"]),
        "auditMinHumans": number(config["analysis"]["min_human_contributors"]),
        "auditDiscoveredRepos": number(selection["repositories"]),
        "auditEvaluated": number(selection["evaluated"]),
        "auditKept": number(selection["kept"]),
        "auditPending": number(selection["pending"]),
        "auditNotFound": number(selection["not_found"]),
        "auditKeptOutside": number(outside["kept_only_from_outside"]),
        "auditKeptOutsideShare": percent(outside["share_of_kept"]),
        "auditUnreachableOutside": number(outside["unreachable_matches"]),
        "auditManualKept": number(discovery["manual"]["kept"]),
        "auditMined": number(mining["mined"]),
        "auditFailed": number(mining["failed"]),
        "auditNotMined": number(mining["selected_not_mined"]),
        "auditMinedFrom": day(mining["mined_from"]),
        "auditMinedTo": day(mining["mined_to"]),
        "auditMinedAfterReference": number(mining["mined_after_reference_date"]),
        "auditOmittedContents": number(sum(mining["content_omitted"].values())),
    }
    unreachable = sum(q["unreachable_matches"] for q in discovery["queries"].values())
    values["auditUnreachable"] = number(unreachable)
    for query in discovery["queries"].values():
        suffix = FILE_TYPE_SUFFIX.get(query["file_type"] or "")
        if suffix is None or f"auditCoverage{suffix}" in values:
            continue
        values[f"auditEstimated{suffix}"] = number(query["estimated_matches"])
        values[f"auditCollected{suffix}"] = number(query["collected_matches"])
        values[f"auditCoverage{suffix}"] = percent(query["estimated_coverage"])
        values[f"auditCollectedUpTo{suffix}"] = number(query["contiguous_up_to"])
        values[f"auditHitRepos{suffix}"] = number(query["repositories"])

    for criterion, effect in selection["criteria"].items():
        name = camel(criterion)
        values[f"auditFail{name}"] = number(effect["fail"])
        values[f"auditFailShare{name}"] = percent(effect["fail_share"])
        values[f"auditOnly{name}"] = number(effect["only_failure"])
    top = top_criterion(selection)
    values["auditTopCriterion"] = (
        criterion_label(top, config["selection"]) if top is not None else MISSING
    )
    values["auditTopCriterionShare"] = (
        percent(selection["criteria"][top]["fail_share"]) if top is not None else MISSING
    )
    examples = selection["only_license"]["top_by_stars"][:3]
    values["auditLicenseExamples"] = (
        ", ".join(rf"\texttt{{{escape(r['full_name'])}}}" for r in examples) or MISSING
    )
    stars = selection["stars"]["kept"] or {}
    values["auditStarsMedianKept"] = number(stars.get("p50"))
    years = {int(year): n for year, n in selection["kept_by_creation_year"].items()}
    recent = sum(n for year, n in years.items() if year >= RELATED_CUTOFF.year)
    values["auditRelatedCutoffYear"] = str(RELATED_CUTOFF.year)
    values["auditKeptSinceRelatedCutoff"] = number(recent)
    values["auditKeptSinceRelatedCutoffShare"] = percent(_share(recent, sum(years.values())))

    for file_type, info in artifacts["by_file_type"].items():
        suffix = FILE_TYPE_SUFFIX[file_type]
        size = info["eligible_size"] or {}
        values[f"auditAtHead{suffix}"] = number(info["at_head"])
        values[f"auditSymlinks{suffix}"] = number(info["symlinks"])
        values[f"auditBelowMin{suffix}"] = number(info["below_min_bytes"])
        values[f"auditEligible{suffix}"] = number(info["eligible"])
        values[f"auditMedianBytes{suffix}"] = number(size.get("p50"))
        values[f"auditAboveCollected{suffix}"] = number(info["eligible_above_collected"])
        values[f"auditAboveCollectedShare{suffix}"] = percent(
            info["eligible_above_collected_share"]
        )
        values[f"auditEligibleRepos{suffix}"] = number(info["repositories_with_eligible"])
        values[f"auditViaOtherTypes{suffix}"] = number(
            info["repositories_reached_only_through_other_types"]
        )
        values[f"auditSmallRoot{suffix}"] = number(info["repositories_with_small_or_symlink_root"])
        values[f"auditSmallRootWithOther{suffix}"] = number(
            info["of_which_with_other_eligible_type"]
        )
    history = audit["history"]
    cut = history["reference_date"] is not None
    for name, key in (
        ("auditCutoffCommits", "commits_after_cutoff"),
        ("auditCutoffRepos", "repositories_with_commits_after_cutoff"),
        ("auditCutoffChanges", "artifact_changes_after_cutoff"),
        ("auditCutoffNotYetCreated", "artifacts_not_yet_created"),
        ("auditCutoffOtherState", "artifacts_with_another_state"),
        ("auditCutoffAuthorsDropped", "identities_dropped"),
        ("auditMinedBeforeCutoff", "mined_before_cutoff"),
        ("auditNoRecordedChanges", "artifacts_without_recorded_changes"),
    ):
        values[name] = number(history[key]) if cut else MISSING
    values["auditMaxDaysMissing"] = (
        f"{history['max_days_missing']:.1f}".replace(".", ",") if cut else MISSING
    )
    for name, key in (
        ("auditEligibleAtHead", "eligible_at_head"),
        (
            "auditEligibleAtCutoff",
            "eligible_at_cutoff",
        ),
    ):
        values[name] = number(sum(history[key]["files"].values())) if cut else MISSING
        values[f"{name}Repos"] = number(history[key]["repositories"]) if cut else MISSING
    concentration, duplicates = artifacts["concentration"], artifacts["duplicates"]
    per_repo = concentration["files_per_repository"] or {}
    values |= {
        "auditEligibleFiles": number(concentration["eligible_files"]),
        "auditEligibleRepos": number(concentration["repositories"]),
        "auditMedianFilesPerRepo": number(per_repo.get("p50")),
        "auditMaxFilesPerRepo": number(concentration["max_files_per_repository"]),
        "auditTopOnePctRepos": number(concentration["top_1pct_repositories"]),
        "auditTopOnePctShare": percent(concentration["top_1pct_share"]),
        "auditDuplicateCopies": number(duplicates["duplicate_copies"]),
        "auditDuplicateShare": percent(duplicates["duplicate_share"]),
    }
    for name in values:
        if not _MACRO_RE.match(name):
            raise ValueError(f"Invalid LaTeX macro name: {name}")
    return values


# --------------------------------------------------------------------------- tables


def top_criterion(selection: Mapping[str, Any]) -> str | None:
    """The criterion most evaluated repositories fail (ties: evaluation order), or ``None`` when
    no criterion rejects anything. The draft names it instead of assuming which one it is."""
    failing = [(effect["fail"], c) for c, effect in selection["criteria"].items() if effect["fail"]]
    if not failing:
        return None
    most = max(fail for fail, _ in failing)
    return next(criterion for fail, criterion in failing if fail == most)


def criterion_label(criterion: str, selection_config: Mapping[str, Any]) -> str:
    labels = {
        "empty": "repositório vazio",
        "fork": "fork",
        "archived": "arquivado",
        "mirror": "espelho (\\emph{mirror})",
        "template": "\\emph{template}",
        "created_after_cutoff": f"criado a partir de {day(selection_config['created_before'])}",
        "license": "licença não aprovada pela OSI",
        "no_code_language": "linguagem principal não é de programação",
        "min_stars": f"menos de {number(selection_config['min_stars'])} estrelas",
        "min_commits": f"menos de {number(selection_config['min_commits'])} commits",
        "inactive": f"sem commits nos últimos {number(selection_config['active_within_days'])} "
        "dias",
        "keyword": "palavra de tutorial ou lista no nome",
    }
    return labels.get(criterion, escape(criterion))


def _table(label: str, caption: str, columns: str, header: str, rows: list[str]) -> str:
    body = "\n".join(f"    {row} \\\\" for row in rows)
    return (
        "\\begin{table}[ht]\n"
        "  \\centering\n"
        f"  \\caption{{{caption}}}\n"
        f"  \\label{{{label}}}\n"
        "  \\small\n"
        f"  \\begin{{tabular}}{{{columns}}}\n"
        "    \\hline\n"
        f"    {header} \\\\\n"
        "    \\hline\n"
        f"{body}\n"
        "    \\hline\n"
        "  \\end{tabular}\n"
        "\\end{table}"
    )


def selection_table(audit: Mapping[str, Any]) -> str:
    selection = audit["selection"]
    config = audit["study_config"]["selection"]
    rows = [
        f"{criterion_label(criterion, config)} & {number(effect['fail'])} & "
        f"{percent(effect['fail_share'])} & {number(effect['only_failure'])}"
        for criterion, effect in selection["criteria"].items()
        if effect["fail"]
    ]
    rows.append(f"\\hline\n    mantidos (todos os critérios) & {number(selection['kept'])} & & ")
    return _table(
        "tab:audit-selection",
        f"Critérios de seleção aplicados aos {number(selection['evaluated'])} repositórios "
        "avaliados. \\emph{Só este} conta os repositórios que falham apenas no critério e "
        "seriam incluídos sem ele.",
        "lrrr",
        "Critério & Falham & \\% & Só este",
        rows,
    )


def discovery_table(audit: Mapping[str, Any]) -> str:
    rows = []
    for query, info in audit["discovery"]["queries"].items():
        name = info["file_type"] or escape(query)
        ranges = "; ".join(f"{number(lo)}--{number(hi)}" for lo, hi in info["covered_ranges"])
        rows.append(
            f"\\texttt{{{name}}} & {number(info['estimated_matches'])} & "
            f"{number(info['collected_matches'])} & {percent(info['estimated_coverage'])} & "
            f"{ranges or MISSING} & {number(info['unreachable_matches'])} & "
            f"{number(info['repositories'])}"
        )
    return _table(
        "tab:audit-discovery",
        "Cobertura da busca de código por tipo de arquivo: resultados estimados pela API, "
        "coletados, faixa de tamanho coletada (bytes), resultados inacessíveis pelo limite de "
        f"{number(audit['study_config']['discovery']['max_results_per_query'])} por consulta e "
        "repositórios encontrados.",
        "lrrrlrr",
        "Arquivo & Estimados & Coletados & Cobertura & Faixa & Inacessíveis & Repos.",
        rows,
    )


def artifact_table(audit: Mapping[str, Any]) -> str:
    rows = []
    for file_type, info in audit["artifacts"]["by_file_type"].items():
        size = info["eligible_size"] or {}
        above = info["eligible_above_collected"]
        above_text = (
            MISSING
            if above is None
            else f"{number(above)} ({percent(info['eligible_above_collected_share'])})"
        )
        rows.append(
            f"\\texttt{{{file_type}}} & {number(info['at_head'])} & {number(info['symlinks'])} "
            f"& {number(info['below_min_bytes'])} & {number(info['eligible'])} & "
            f"{number(size.get('p50'))} & {above_text} & "
            f"{number(info['repositories_reached_only_through_other_types'])}"
        )
    minimum = number(audit["study_config"]["analysis"]["min_artifact_bytes"])
    return _table(
        "tab:audit-artifacts",
        "Arquivos no HEAD dos repositórios minerados, antes do filtro de autores humanos: "
        "\\emph{symlinks}, arquivos com menos de "
        f"{minimum} bytes, elegíveis e sua mediana de tamanho (bytes), elegíveis maiores que "
        "a faixa coletada pela busca, e repositórios cujos arquivos do tipo só foram alcançados "
        "pela busca de outro tipo.",
        "lrrrrrrr",
        f"Arquivo & HEAD & Symlinks & $<${minimum} & Elegíveis & Mediana & Acima da faixa "
        "& Via outro tipo",
        rows,
    )


# --------------------------------------------------------------------------- files


def _header(audit: Mapping[str, Any]) -> list[str]:
    return [
        "% Generated by `agm audit`: do not edit, run the audit again.",
        f"% Bronze export: {audit['bronze_dir']} (exported {audit.get('exported_at')})",
        f"% Code version: {audit.get('code_version')}; study.yaml sha256: "
        f"{audit['study_config_hash']}",
    ]


def audit_tex(audit: Mapping[str, Any]) -> str:
    lines = _header(audit)
    lines += ["% Load once, in the preamble: \\input{audit}", ""]
    lines += [f"\\newcommand{{\\{name}}}{{{value}}}" for name, value in macro_values(audit).items()]
    lines.append("")
    for name, table in (
        ("auditTableSelection", selection_table(audit)),
        ("auditTableDiscovery", discovery_table(audit)),
        ("auditTableArtifacts", artifact_table(audit)),
    ):
        lines += [f"\\newcommand{{\\{name}}}{{%", table, "}", ""]
    return "\n".join(lines)


def _history_text(history: Mapping[str, Any]) -> str:
    """The threats-to-validity sentences about when the repositories were mined."""
    if not history["enabled"]:
        return (
            "A mineração ocorreu entre \\auditMinedFrom{} e \\auditMinedTo{}, ao longo de várias "
            "semanas; \\auditMinedAfterReference{} repositórios foram minerados depois da data "
            "de referência (\\auditReferenceDate) e têm histórico posterior a ela."
        )
    text = (
        "A mineração ocorreu entre \\auditMinedFrom{} e \\auditMinedTo{}. Para que todos os "
        "repositórios fossem observados no mesmo instante, a análise considera apenas os commits "
        "feitos até o fim da data de referência (\\auditReferenceDate): foram descartados "
        "\\auditCutoffCommits{} commits posteriores que alteraram artefatos, em "
        "\\auditCutoffRepos{} repositórios, e cada artefato foi analisado no estado em que estava "
        "nessa data. "
    )
    if history["mined_before_cutoff"]:
        text += (
            "Os \\auditMinedBeforeCutoff{} repositórios minerados antes do fim dessa data podem "
            "não ter até \\auditMaxDaysMissing{} dia de histórico. "
        )
    return text + (
        "Duas informações não puderam ser cortadas: o total de commits de cada autor e seu perfil "
        "de atividade, usados para classificar os papéis dos autores, cobrem o histórico inteiro "
        "do clone; e os metadados do GitHub (estrelas, licença, linguagem) foram coletados na "
        "seleção."
    )


def draft_tex(audit: Mapping[str, Any]) -> str:
    """Draft paragraphs (Portuguese) built on the macros of ``audit.tex``."""
    discovery = audit["discovery"]
    complete = all(q["complete"] for q in discovery["queries"].values())
    unreachable = sum(q["unreachable_matches"] for q in discovery["queries"].values())
    lines = _header(audit)
    lines += [
        "% DRAFT: copy into the paper and edit there. The numbers are macros of audit.tex.",
        "% Current warnings (resolve or report them before the final version):",
    ]
    lines += [f"%   - {warning}" for warning in audit["warnings"]] or ["%   - none"]
    lines += [
        "",
        "% ---- Metodologia: coleta -------------------------------------------------",
        "",
    ]
    if not complete:
        lines.append("% TODO: the discovery is incomplete (see Table tab:audit-discovery).")
    lines += [
        "\\paragraph{Descoberta.} Os repositórios candidatos foram encontrados pela API de busca "
        "de código do GitHub, com uma consulta por tipo de arquivo (\\texttt{CLAUDE.md}, "
        "\\texttt{AGENTS.md} e \\texttt{SKILL.md} em \\texttt{.claude/skills}). Como a API "
        "devolve no máximo \\auditResultCap{} resultados por consulta, cada consulta foi "
        "dividida por faixas de tamanho de arquivo, entre \\auditSizeMin{} e \\auditSizeMax{} "
        "bytes, até que cada faixa coubesse nesse limite. Arquivos menores que \\auditSizeMin{} "
        "bytes não foram buscados, porque ficariam fora da amostra pelo critério de tamanho "
        "descrito adiante. "
        + (
            "Nenhuma faixa ultrapassou o limite, de modo que todos os resultados indicados pela "
            "API puderam ser coletados. "
            if unreachable == 0
            else "Mesmo assim, \\auditUnreachable{} resultados ficaram inacessíveis em faixas de "
            "um único byte que ultrapassaram o limite. "
        )
        + "A busca encontrou \\auditDiscoveredRepos{} repositórios distintos "
        "(Tabela~\\ref{tab:audit-discovery}).",
        "",
        "\\paragraph{Seleção.} Dos \\auditEvaluated{} repositórios com metadados disponíveis, "
        "\\auditKept{} atenderam a todos os critérios de seleção "
        "(Tabela~\\ref{tab:audit-selection}). "
        + (
            "O critério que mais exclui repositórios é \\emph{\\auditTopCriterion}, que "
            "atinge \\auditTopCriterionShare{} dos avaliados. "
            if top_criterion(audit["selection"]) is not None
            else ""
        )
        + "A tabela também mostra, para cada critério, "
        "quantos repositórios seriam incluídos se apenas ele fosse removido. A exigência de "
        "licença aprovada pela OSI exclui sozinha \\auditOnlyLicense{} repositórios, entre eles "
        "projetos populares sem licença detectada pelo GitHub ou com licença própria, como "
        "\\auditLicenseExamples.",
        "",
        "\\paragraph{Mineração.} Os \\auditMined{} repositórios selecionados foram clonados e "
        "minerados entre \\auditMinedFrom{} e \\auditMinedTo{}; \\auditFailed{} não puderam ser "
        "minerados. "
        + (
            "O histórico de cada repositório foi cortado no fim da data de referência "
            "(\\auditReferenceDate), e cada artefato é analisado no estado em que estava nessa "
            "data. "
            if audit["history"]["enabled"]
            else ""
        )
        + "Foram mantidos os \\texttt{CLAUDE.md}, "
        "\\texttt{AGENTS.md} e \\texttt{SKILL.md} com pelo menos \\auditMinArtifactBytes{} bytes "
        "que não são \\emph{symlinks}, em repositórios com pelo menos \\auditMinHumans{} autores "
        "humanos (Tabela~\\ref{tab:audit-artifacts}).",
        "",
        "% ---- Ameaças à validade -------------------------------------------------",
        "",
        "\\paragraph{Validade de construto.} A população observável é definida pela busca de "
        "código do GitHub, que indexa apenas o branch padrão e arquivos menores que "
        "\\auditSizeMax{} bytes, e cujos resultados não são determinísticos. O tamanho mínimo de "
        "\\auditMinArtifactBytes{} bytes exclui arquivos que apenas apontam para outro: "
        "\\auditSmallRootClaude{} repositórios minerados têm um \\texttt{CLAUDE.md} na raiz "
        "menor que esse limite ou \\emph{symlink}, e \\auditSmallRootWithOtherClaude{} deles têm "
        "outro arquivo de instruções elegível. Nossos resultados descrevem, portanto, arquivos "
        "de instruções substantivos, e não todos os arquivos com esses nomes.",
        "",
        "\\paragraph{Validade interna.} " + _history_text(audit["history"]) + " "
        "Os arquivos elegíveis se concentram em poucos repositórios: "
        "os \\auditTopOnePctRepos{} repositórios com mais arquivos (1\\%) reúnem "
        "\\auditTopOnePctShare{} deles, enquanto a mediana é de \\auditMedianFilesPerRepo{} "
        "por repositório. Por isso, reportamos as estatísticas também por repositório. "
        "\\auditDuplicateShare{} dos arquivos elegíveis são cópias idênticas de outro arquivo.",
        "",
        "\\paragraph{Validade externa.} A amostra contém projetos de código aberto populares "
        "(mediana de \\auditStarsMedianKept{} estrelas), ativos e com licença aprovada pela "
        "OSI; os resultados não se estendem a repositórios privados, pouco populares ou sem "
        "licença, nem a outras ferramentas de agentes. Diferentemente de estudos anteriores, "
        "que se limitaram a projetos criados antes de \\auditRelatedCutoffYear, incluímos "
        "projetos criados até \\auditCreatedBefore: \\auditKeptSinceRelatedCutoffShare{} dos "
        "repositórios mantidos foram criados a partir de \\auditRelatedCutoffYear.",
        "",
    ]
    return "\n".join(lines)
