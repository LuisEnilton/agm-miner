"""The Docker image and the compose service that run the CLI without a local Python."""

from __future__ import annotations

import re
from pathlib import Path

import pytest
import yaml

from agm_miner.runs import code_version

ROOT = Path(__file__).resolve().parents[1]


def test_code_version_comes_from_the_image_when_there_is_no_git(monkeypatch) -> None:
    code_version.cache_clear()
    monkeypatch.setenv("AGM_CODE_VERSION", "0123abc")
    try:
        assert code_version() == "0123abc"
        code_version.cache_clear()
        monkeypatch.setenv("AGM_CODE_VERSION", "unknown")  # the build argument's default
        assert code_version() != "unknown"
    finally:
        code_version.cache_clear()


def test_dockerfile_has_a_recent_git_and_runs_agm() -> None:
    dockerfile = (ROOT / "Dockerfile").read_text()
    # git >= 2.44 (--no-lazy-fetch): Debian trixie, not bookworm (2.39).
    assert re.search(r"^FROM python:3\.11-slim-trixie$", dockerfile, re.MULTILINE)
    assert "install -y --no-install-recommends git" in dockerfile
    assert 'ENTRYPOINT ["agm"]' in dockerfile
    assert "ENV AGM_CODE_VERSION=${CODE_VERSION}" in dockerfile
    lock = (ROOT / "poetry.lock").read_text()
    assert "@generated by Poetry 2." in lock.splitlines()[0]
    assert 'pip install "poetry==2.' in dockerfile


def test_compose_service_points_to_the_compose_database() -> None:
    compose = yaml.safe_load((ROOT / "docker-compose.yml").read_text())
    agm = compose["services"]["agm"]
    db = compose["services"]["db"]["environment"]
    assert agm["profiles"] == ["tool"]  # `docker compose up -d db` does not start it
    assert agm["build"]["args"]["CODE_VERSION"] == "${AGM_CODE_VERSION:-unknown}"
    url = agm["environment"]["DATABASE_URL"]
    assert f"@db:5432/{db['POSTGRES_DB']}" in url
    assert f"{db['POSTGRES_USER']}:{db['POSTGRES_PASSWORD']}@" in url
    assert agm["volumes"] == ["./data:/data"] and agm["environment"]["DATA_DIR"] == "/data"


@pytest.mark.parametrize("ignored", [".env", "data", ".git", "Artigos", ".venv"])
def test_secrets_and_data_stay_out_of_the_image(ignored: str) -> None:
    lines = (ROOT / ".dockerignore").read_text().splitlines()
    assert ignored in lines
